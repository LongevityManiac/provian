"""The Python meter wire reproduces the relay's pinned vectors byte for byte.

``docs/audit/meter-wire-vectors.json`` was generated by the relay's own ``meter-wire.ts``
(``provian-backend/scripts/generate-meter-wire-vectors.ts``); the relay, the TypeScript SDK and the
app reproduce it in their own suites. Every hash below is the relay's, never one this suite wrote.
"""

import json

import pytest

from provian.meter_wire import (
    CanonicalJsonError,
    act_leaf_of,
    act_record_of,
    acts_root_of,
    batch_hash_of,
    batch_leaf_of,
    build_batch,
    canonical_json,
    hardware_nonce_of_act,
    merkle_proof_of,
    pe_hash_of,
    validate_batch_shape,
    verify_act_chain,
    verify_act_inclusion,
    verify_merkle_proof_of,
)

from .conftest import METER_VECTORS_PATH

with open(METER_VECTORS_PATH, encoding="utf-8") as _fh:
    V = json.load(_fh)


def test_the_vector_population_is_the_relays_and_non_empty():
    assert V["schema"] == "provian.meter-wire-vectors.v1"
    assert len(V["pes"]) == 3 and len(V["pe_hashes"]) == 3 and len(V["act_proofs"]) == 3


def test_canonical_json():
    assert canonical_json(V["canonical_json"]["input"]) == V["canonical_json"]["output"]


def test_pe_hashes_act_records_and_act_leaves():
    assert [pe_hash_of(pe) for pe in V["pes"]] == V["pe_hashes"]
    assert [act_record_of(pe) for pe in V["pes"]] == V["acts"]
    assert [act_leaf_of(a) for a in V["acts"]] == V["act_leaves"]


def test_hardware_nonce():
    assert hardware_nonce_of_act(act_record_of(V["pes"][2])) == V["hardware_nonce_c"]


def test_the_batch_its_hash_its_proofs_and_its_leaf():
    b = V["batch"]
    built = build_batch(b["device_id"], b["seq"], b["prev_batch_hash"], b["created_at_ms"], V["pes"])
    assert built == b
    assert acts_root_of(V["acts"]) == b["acts_root"]
    assert batch_hash_of(built) == V["batch_hash"]
    assert [merkle_proof_of(V["act_leaves"], i) for i in range(3)] == V["act_proofs"]
    assert batch_leaf_of(b["device_id"], "agent_vector", b["seq"], V["batch_hash"], b["acts_root"]) == V["batch_leaf"]
    for i, leaf in enumerate(V["act_leaves"]):
        assert verify_merkle_proof_of(leaf, V["act_proofs"][i], b["acts_root"])
    assert validate_batch_shape(b) is None
    assert verify_act_chain("genesis", V["acts"]) is None


def test_sealed_copies_are_not_part_of_the_batch_hash():
    b = V["batch"]
    sealed = build_batch(b["device_id"], b["seq"], b["prev_batch_hash"], b["created_at_ms"], V["pes"],
                         sealed=[{"to": "linked_human", "pe_id": "pe_vector_a", "box": "AQID"}])
    assert batch_hash_of(sealed) == V["batch_hash"]
    assert validate_batch_shape(sealed) is None


def test_inclusion_hop_one_from_the_pe_itself():
    b = V["batch"]
    proof = {"act_proof": V["act_proofs"][1], "acts_root": b["acts_root"],
             "batch": {"device_id": b["device_id"], "actor_id": "agent_vector", "seq": 1, "batch_hash": V["batch_hash"]}}
    assert verify_act_inclusion(V["pes"][1], proof) == V["batch_leaf"]


# --- RED controls: each check above can fail -----------------------------------------

def test_red_an_edited_pe_free_text_changes_its_hash_but_not_its_pricing():
    pe = dict(V["pes"][0], description="edited")
    assert pe_hash_of(pe) != V["pe_hashes"][0]
    assert act_record_of(pe)["pricing"] == V["acts"][0]["pricing"]  # free text never priced


def test_red_a_naive_canonicalizer_disagrees_with_the_relay():
    naive = json.dumps(V["canonical_json"]["input"], sort_keys=True, separators=(",", ":"))
    assert naive != V["canonical_json"]["output"]


def test_red_canonical_json_refuses_what_could_never_be_proven():
    for bad in (float("nan"), float("inf"), 2 ** 53, {1: "x"}, object()):
        with pytest.raises(CanonicalJsonError):
            canonical_json(bad)


def test_red_the_relays_shape_and_chain_checks_catch_tampering():
    b = dict(V["batch"])
    b["acts"] = [dict(a) for a in V["acts"]]
    b["acts"][1] = dict(b["acts"][1], pricing={"metadata": {"tool_count": 99}})
    assert validate_batch_shape(b) == ("acts_root_mismatch", None)
    assert validate_batch_shape(dict(V["batch"], seq=0)) == ("bad_seq", None)
    leaky = dict(V["acts"][0], pricing=dict(V["acts"][0]["pricing"], description="x"))
    assert validate_batch_shape(dict(V["batch"], acts=[leaky], acts_root=acts_root_of([leaky]))) == ("bad_act", 0)
    assert verify_act_chain("genesis", [V["acts"][0], V["acts"][2]]) == 1
    assert not verify_merkle_proof_of(V["act_leaves"][0], V["act_proofs"][1], V["batch"]["acts_root"])
