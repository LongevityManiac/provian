/**
 * WP1 PVT-native cost proposal.  Values are either integer atomic units or
 * same-unit basis points. No entry derives a PVT quantity from another asset.
 * The rows are PROPOSED PARAMETER CHOICES only. Earlier drafts attached the
 * same institution-wide source paths to every row; that did not semantically
 * prove each current-live-behavior statement. Those claims are now explicitly
 * unverified and cannot serve as an approval basis until row-specific evidence
 * is supplied. The catalog is not connected to deployed runtime configuration.
 */
import type {
  ApprovalFlag,
  BasisPointCostRule,
  CostActivation,
  CostAuthority,
  CostDisposition,
  CostSnapshotTiming,
  ProposedPVTNativeCostCatalog,
  ProposedPVTNativeCostEntry,
} from './types';

const SEVEN_DAYS_SECONDS = 604_800;

const DEFERRED_PVT9_AUTHORITY =
  'deferred_not_gate_1_approved_requires_separate_pvt9_authority_table';

const REQUIRES_APPROVAL: ApprovalFlag = {
  status: 'requires_frank_approval',
  rationale: 'Initial value or proposed envelope requires Frank approval before activation.',
};

const REQUIRES_AFFORDABILITY_APPROVAL: ApprovalFlag = {
  status: 'requires_affordability_and_frank_approval',
  rationale: 'The value must be pressure-tested against reachable issuance before Frank approval.',
};

function authority(current: string): CostAuthority {
  return { current, proposed: DEFERRED_PVT9_AUTHORITY };
}

function activation(currentDelaySeconds: number, proposedDelaySeconds = SEVEN_DAYS_SECONDS): CostActivation {
  return {
    current_delay_seconds: currentDelaySeconds,
    proposed_minimum_delay_seconds: proposedDelaySeconds,
    effective_policy_version_required: true,
    effective_boundary: 'effective_at',
    prospective_only: true,
  };
}

function snapshot(current: CostSnapshotTiming, proposed: CostSnapshotTiming): ProposedPVTNativeCostEntry['snapshot'] {
  return { current, proposed };
}

function basisPoints(
  initialBps: number,
  minimumBps: number,
  maximumBps: number,
  calculationBasis: string,
  rounding: BasisPointCostRule['rounding'] = 'floor_to_atomic_unit',
): BasisPointCostRule {
  return {
    kind: 'basis_points',
    initial_bps: initialBps,
    minimum_bps: minimumBps,
    maximum_bps: maximumBps,
    calculation_basis: calculationBasis,
    rounding,
  };
}

function disposition(
  burn: string,
  lock: string,
  recipient: string,
  refund: string,
  slash: string,
): CostDisposition {
  return {
    burn,
    lock,
    recipient,
    refund,
    slash,
    cost_pe_mint_disposition: 'record_only',
  };
}

