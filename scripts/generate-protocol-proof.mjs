#!/usr/bin/env node
import { createRequire } from 'node:module';
import { readFileSync, writeFileSync, mkdtempSync, rmSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { tmpdir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { execFileSync } from 'node:child_process';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const dependencyRoots = ['provian-agent-sdk', 'provian-mcp', '.'].map(name => join(root, name, 'node_modules'));
const require = createRequire(import.meta.url);
const { build } = require(require.resolve('esbuild', { paths: dependencyRoots }));
const targets = ['provian-agent-sdk/src/protocol-proof.generated.ts', 'src/core/protocol/proof.generated.ts',
  'provian-mcp/src/core/protocol-proof.generated.ts', 'provian-backend/src/mcp/core/protocol-proof.generated.ts'];
const target = join(root, targets[0]);
let previous;
try { previous = JSON.parse(readFileSync(target, 'utf8').split(' = ')[1].trim().replace(/;$/, '')); } catch { /* First build. */ }
const temp = mkdtempSync(join(tmpdir(), 'provian-proof-build-'));
try {
  const entry = `import {buildProtocolProof} from './src/protocol-proof-build';
import {protocolRpc} from './src/protocol-rpc';
import {guardedFetch} from './src/guarded-fetch';
import {PROTOCOL_POINTER_PIN as pin} from './src/protocol-pointer-pin.generated';
const urls=['https://mainnet.base.org','https://base.drpc.org'];
(async()=>{if(!pin.address||!pin.runtimeHash)throw Error('protocol_pointer_not_deployed');
const proof=await buildProtocolProof(urls.map(url=>protocolRpc(url,async(u,init)=>{const r=await guardedFetch(u,init);if(!r.ok)console.error(new URL(u).host,JSON.parse(init.body).method,'HTTP',r.status,'Retry-After',r.headers.get('retry-after'));return r;})),pin.address,pin.runtimeHash,urls,${JSON.stringify(previous) ?? 'undefined'});
process.stdout.write(proof);})().catch(e=>{console.error(e.message);process.exitCode=1;});`;
  const outfile = join(temp, 'generate.cjs');
  await build({ stdin: { contents: entry, resolveDir: join(root, 'provian-agent-sdk'), loader: 'ts' },
    outfile, bundle: true, platform: 'node', format: 'cjs', logLevel: 'silent', nodePaths: dependencyRoots });
  const proof = execFileSync(process.execPath, [outfile], { encoding: 'utf8', timeout: 300_000, maxBuffer: 1024 * 1024 });
  const content = '// Generated by scripts/generate-protocol-proof.mjs from two independent public providers.\n'
    + '// A candidate only: every use requires fresh live confirmation.\n'
    + `export const BUILT_IN_PROTOCOL_PROOF = ${JSON.stringify(proof)};\n`;
  for (const name of targets) writeFileSync(join(root, name), content);
  console.log(`Built-in protocol proof: revision ${JSON.parse(proof).revision}, finalized anchor ${JSON.parse(proof).blockHash}`);
} finally { rmSync(temp, { recursive: true, force: true }); }
