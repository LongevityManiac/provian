#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

export const LOCALES = ['en', 'es', 'fr', 'hi', 'id', 'ja', 'ko', 'pt', 'sw', 'tl', 'vi', 'zh'];
const root = resolve(import.meta.dirname, '..');
const readJson = (path) => JSON.parse(readFileSync(path, 'utf8'));
const placeholders = (text) => [...text.matchAll(/\{\{[^}]+\}\}/g)].map(([match]) => match).sort();
// Numeric facts (amounts, rates) must survive translation exactly and IN ORDER, so a
// translation that swaps two amounts ("75 … 25" → "25 … 75") fails. The one allowance is a
// calendar date: languages order a date's parts differently ("December 31, 2026" vs
// "2026年12月31日"), so the numbers inside the English's dates are compared as a multiset,
// set aside, and the remaining facts compared in order. A calendar month written as a
// numeral in CJK or Vietnamese (the 12 in 12月 / 12월 / tháng 12) is part of how those
// languages spell a date, not an extra fact, so it is not counted.
const MONTH_NUMERAL = /[0-9]{1,2}(?=\s*[月월])|(?<=tháng\s)[0-9]{1,2}/g;
const ENGLISH_DATE = /\b(?:January|February|March|April|May|June|July|August|September|October|November|December) ([0-9]{1,2}), ([0-9]{4})\b/g;
const numberList = (text) => text.replace(MONTH_NUMERAL, '').match(/[0-9]+(?:\.[0-9]+)?/g) ?? [];
const dateParts = (englishText) => [...englishText.matchAll(ENGLISH_DATE)].flatMap(([, day, year]) => [day, year]);
const withoutEach = (list, remove) => {
  const out = [...list];
  for (const value of remove) {
    const at = out.indexOf(value);
    if (at === -1) return null;
    out.splice(at, 1);
  }
  return out;
};
export function numericFactsMatch(value, englishValue) {
  const dates = dateParts(englishValue);
  const english = withoutEach(numberList(englishValue), dates);
  const translated = withoutEach(numberList(value), dates);
  return translated !== null && JSON.stringify(translated) === JSON.stringify(english);
}
export function validateNarrative(copy, english, locale) {
  const keys = Object.keys(english).sort();
  if (JSON.stringify(Object.keys(copy).sort()) !== JSON.stringify(keys)) throw new Error(`${locale}: narrative keys differ from English`);
  for (const key of keys) {
    const value = copy[key];
    if (typeof value !== 'string' || !value.trim()) throw new Error(`${locale}: empty ${key}`);
    if (JSON.stringify(placeholders(value)) !== JSON.stringify(placeholders(english[key]))) throw new Error(`${locale}: placeholders differ for ${key}`);
    if (!numericFactsMatch(value, english[key])) throw new Error(`${locale}: numeric facts differ for ${key}`);
    if (value.split('\n\n').length !== english[key].split('\n\n').length) throw new Error(`${locale}: paragraph structure differs for ${key}`);
    if (locale !== 'en' && value === english[key]) throw new Error(`${locale}: untranslated ${key}`);
  }
}
