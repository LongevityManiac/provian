#!/usr/bin/env node
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
const root = resolve(import.meta.dirname, '..');
const source = readFileSync(resolve(root, 'docs/PE_GENERATION_MODEL.md'), 'utf8');
// Both source and mirror are one directory below the repository root. Relative
// links into docs need to keep resolving from the library edition in reference/.
const body = source.replace(/\]\((?:\.\/)?([^/):]+\.md)(#[^)]*)?\)/g, '](../docs/$1$2)');
const output = '<!-- Generated by scripts/generate-pe-generation-model.mjs from docs/PE_GENERATION_MODEL.md. DO NOT EDIT. -->\n\n' + body;
const path = resolve(root, 'reference/PE_Generation_Model_v5.md');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw new Error('PE Generation Model mirror is stale');
  console.log('PE Generation Model mirror verified.');
} else { writeFileSync(path, output); console.log('PE Generation Model mirror generated.'); }
