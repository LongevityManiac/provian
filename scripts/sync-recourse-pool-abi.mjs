import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { Interface } from 'ethers';
const root = resolve(import.meta.dirname, '..');
const artifact = JSON.parse(readFileSync(resolve(root, 'contracts/out/ProvianMemberRecoursePool.sol/ProvianMemberRecoursePool.json'), 'utf8'));
const iface = new Interface(artifact.abi);
const fragments = iface.fragments.filter(f => f.type === 'function' || f.type === 'event').map(f => f.format('full')).sort();
const output = '// Generated by scripts/sync-recourse-pool-abi.mjs from the compiled Recourse Pool.\n'
  + 'import { Interface } from "ethers";\nexport const RECOURSE_POOL_ABI = new Interface('
  + JSON.stringify(fragments, null, 2) + ');\n';
const path = resolve(root, 'provian-agent-sdk/src/recourse-pool-abi.ts');
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== output) throw Error('recourse_pool_abi_drift');
} else writeFileSync(path, output);
console.log(`Recourse Pool ABI: ${fragments.length} functions/events ${process.argv.includes('--check') ? 'verified' : 'written'}`);
