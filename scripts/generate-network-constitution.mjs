#!/usr/bin/env node
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { LOCALES } from './generate-app-narrative.mjs';

const root = resolve(import.meta.dirname, '..');
const sourcePath = resolve(root, 'NETWORK_CONSTITUTION.md');
const outputPath = resolve(root, 'src/generated/networkConstitution.ts');
export const sourceHash = (source) => createHash('sha256').update(source, 'utf8').digest('hex');
const contentLines = (source) => source.replace(/\r\n/g, '\n').split('\n').filter((line) => line.trim() && !/^<!-- source-sha256:/.test(line));
function lineShape(line) {
  if (/^#{1,2} /.test(line)) return `heading:${line.match(/^#+/)[0].length}`;
  if (/^\|/.test(line)) return `table:${line.split('|').length}`;
  if (/^\d+\. /.test(line)) return `clause:${line.match(/^\d+/)[0]}`;
  if (/^[-*] /.test(line)) return 'bullet';
  return 'paragraph';
}
export function validateTranslation(source, translation, locale) {
  const hash = /^<!-- source-sha256: ([a-f0-9]{64}) -->$/m.exec(translation)?.[1];
  if (hash !== sourceHash(source)) throw new Error(`${locale}: Constitution translation has a stale source hash`);
  const original = contentLines(source);
  const translated = contentLines(translation);
  if (original.length !== translated.length) throw new Error(`${locale}: Constitution line/block count differs (${translated.length} vs ${original.length})`);
  original.forEach((line, i) => {
    const target = translated[i];
    if (lineShape(line) !== lineShape(target)) throw new Error(`${locale}: Constitution structure differs at block ${i + 1}`);
    if (line.startsWith('#')) {
      const roman = (value) => value.match(/(?<![\p{L}\p{N}])(?:XIII|XII|XI|IX|VIII|VII|VI|IV|III|II|X|V|I)(?![\p{L}\p{N}])/gu) || [];
      if (JSON.stringify(roman(line)) !== JSON.stringify(roman(target))) throw new Error(`${locale}: article/part order differs at block ${i + 1}`);
    }
    // Values, dates, version labels, and referenced filenames must survive translation.
    const numbers = (value) => value.match(/\d+(?:\.\d+)?/g) || [];
    const code = (value) => [...value.matchAll(/`([^`]+)`/g)].map((match) => match[1]);
    if (JSON.stringify(numbers(line)) !== JSON.stringify(numbers(target))) throw new Error(`${locale}: numeric facts differ at block ${i + 1}`);
    if (JSON.stringify(code(line)) !== JSON.stringify(code(target))) throw new Error(`${locale}: source references differ at block ${i + 1}`);
    if (line === target && line.length > 80 && !line.startsWith('|')) throw new Error(`${locale}: untranslated Constitution block ${i + 1}`);
  });
}
function plain(markdown) {
  return markdown.replace(/^>\s?/, '').replace(/^[-*]\s+/, '• ')
    .replace(/\[([^\]]+)\]\([^\)]+\)/g, '$1').replace(/\*\*([^*]+)\*\*/g, '$1')
    .replace(/\*([^*]+)\*/g, '$1').replace(/`([^`]+)`/g, '$1')
    .replace(/0x[0-9a-fA-F]{40}/g, (address) => `${address.slice(0, 10)}…${address.slice(-4)}`).trimEnd();
}
export function parseCharter(source) {
  const lines = source.replace(/\r\n/g, '\n').split('\n').filter((line) => !/^<!-- source-sha256:/.test(line));
  const title = lines.find((line) => line.startsWith('# '))?.slice(2).trim();
  const statusLine = lines.find((line) => line.startsWith('**'));
  if (!title || !statusLine) throw new Error('Constitution needs a title and status');
  const sections = [];
  let current = null;
  for (const line of lines) {
    const heading = /^(#{1,2})\s+(.+)$/.exec(line);
    if (heading) {
      if (heading[1].length === 1 && heading[2].trim() === title) continue;
      current = { level: heading[1].length, title: plain(heading[2].trim()), body: [] };
      sections.push(current);
      continue;
    }
    if (!current) {
      // The status box already has its own localized text; no extra English heading.
      current = { level: 1, title: '', body: [] };
      sections.push(current);
    }
    if (line === statusLine) continue;
    if (/^---\s*$/.test(line) || /^\|[-:| ]+\|$/.test(line)) continue;
    current.body.push(plain(line));
  }
  return { title, status: plain(statusLine), sections: sections.map((section) => ({ ...section, body: section.body.join('\n').replace(/\n{3,}/g, '\n\n').trim() })) };
}
export function generate(source, translations) {
  const charters = { en: parseCharter(source) };
  for (const locale of LOCALES.filter((item) => item !== 'en')) {
    if (!translations[locale]) throw new Error(`Missing Constitution translation: ${locale}`);
    validateTranslation(source, translations[locale], locale);
    charters[locale] = parseCharter(translations[locale]);
  }
  return `/* AUTO-GENERATED by scripts/generate-network-constitution.mjs. DO NOT EDIT. */\n`
    + `export const NETWORK_CONSTITUTION_SOURCE = 'NETWORK_CONSTITUTION.md' as const;\n`
    + `export const NETWORK_CONSTITUTION_SOURCE_SHA256 = '${sourceHash(source)}' as const;\n`
    + `export interface NetworkCharter { title: string; status: string; sections: { level: number; title: string; body: string }[] }\n`
    + `export const NETWORK_CONSTITUTION_LOCALES: Record<string, NetworkCharter> = ${JSON.stringify(charters, null, 2)};\n`
    + `export const NETWORK_CONSTITUTION_TITLE = NETWORK_CONSTITUTION_LOCALES.en.title;\n`
    + `export const NETWORK_CONSTITUTION_STATUS = NETWORK_CONSTITUTION_LOCALES.en.status;\n`
    + `export const NETWORK_CONSTITUTION_SECTIONS = NETWORK_CONSTITUTION_LOCALES.en.sections;\n`
    + `export function getNetworkConstitution(language: string): NetworkCharter {\n  return NETWORK_CONSTITUTION_LOCALES[language.split(/[-_]/)[0]] ?? NETWORK_CONSTITUTION_LOCALES.en;\n}\n`;
}
export function generateConstitution(check = false) {
  const source = readFileSync(sourcePath, 'utf8');
  const translations = Object.fromEntries(LOCALES.filter((locale) => locale !== 'en').map((locale) => [locale, readFileSync(resolve(root, `docs/translations/network-constitution/${locale}.md`), 'utf8')]));
  const output = generate(source, translations);
  if (check) {
    if (readFileSync(outputPath, 'utf8') !== output) throw new Error('Constitution mirror is stale; run npm run constitution:generate');
  } else writeFileSync(outputPath, output);
  console.log(`Network Constitution ${check ? 'verified' : 'generated'} for ${LOCALES.length} locales.`);
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateConstitution(process.argv.includes('--check'));
